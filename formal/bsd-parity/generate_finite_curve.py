#!/usr/bin/env python3
"""Emit transparent finite Lean certificates; Lean, not this script, checks them."""
from pathlib import Path

POINTS = [(6, -1), (4, 3), (5, -2), (7, 3)]
CASES = [(5, 10, (1, 0), [9, 5, 8, 7]),
         (13, 20, (0, 4), [6, 8, 17, 10]),
         (19, 28, (0, 2), [9, 21, 5, 25])]

out = ['''import Mathlib.AlgebraicGeometry.EllipticCurve.Affine.Point
import Mathlib.Algebra.Field.ZMod
import Mathlib.GroupTheory.OrderOfElement
import Mathlib.Tactic.NormNum

/-!
Certificates in Mathlib's actual nonsingular affine-point group for the curve
y² + xy = x³ - x² - 79x + 289. All finite decisions use kernel reduction.
No native_decide, custom axiom, or unproved certificate is used.
Generated by generate_finite_curve.py; the generated file is the proof source.
-/

namespace BSDImprovements

open WeierstrassCurve.Affine

deriving instance DecidableEq for WeierstrassCurve.Affine.Point

def curve (R : Type*) [CommRing R] : WeierstrassCurve.Affine R :=
  ⟨1, -1, 0, -79, 289⟩

def coordinates {R : Type*} [CommRing R] : (curve R).Point → Option (R × R)
  | .zero => none
  | @Point.some _ _ _ x y _ => some (x,y)

theorem coordinates_injective {R : Type*} [CommRing R] :
    Function.Injective (coordinates (R := R)) := by
  intro P Q h
  cases P <;> cases Q <;> simp_all [coordinates]
''']

def num(x):
    return str(x) if x >= 0 else f'({x})'

for p, order, generator, logs in CASES:
    out.append(f'instance : Fact (Nat.Prime {p}) := ⟨by decide⟩\n')
    for name, (x,y) in [(f'gen{p}', generator)] + [
            (f'p{i}mod{p}', point) for i,point in enumerate(POINTS, 1)]:
        out.append(f'''def {name} : (curve (ZMod {p})).Point :=
  .some (show (curve (ZMod {p})).Nonsingular {num(x)} {num(y)} by
    rw [nonsingular_iff, equation_iff]; decide +kernel)
''')
    for i,log in enumerate(logs,1):
        out.append(f'''theorem log_p{i}_mod{p} : ({log} : ℕ) • gen{p} = p{i}mod{p} := by
  decide +kernel
''')
    out.append(f'''theorem generator_annihilated_mod{p} : ({order} : ℕ) • gen{p} = 0 := by
  decide +kernel

theorem generator_order_mod{p} : addOrderOf gen{p} = {order} := by
  apply (addOrderOf_eq_iff (by decide : 0 < {order})).mpr
  refine ⟨generator_annihilated_mod{p}, ?_⟩
  have h : ∀ n : Fin {order}, 0 < n.val → n.val • gen{p} ≠ 0 := by decide +kernel
  intro n hn hpos
  exact h ⟨n, hn⟩ hpos

theorem coordinates_exhaustive_mod{p} :
    ∀ x y : ZMod {p}, y^2 + x*y = x^3 - x^2 - 79*x + 289 →
      ∃ n : Fin {order}, coordinates (n.val • gen{p}) = some (x,y) := by
  decide +kernel

theorem generator_surjective_mod{p} :
    Function.Surjective (fun n : Fin {order} => n.val • gen{p}) := by
  intro P
  cases P with
  | zero => exact ⟨0, by simp [Point.zero_def]⟩
  | @some x y h =>
    have heq := (equation_iff ..).mp h.left
    have heq' : y^2 + x*y = x^3 - x^2 - 79*x + 289 := by
      simpa [curve, sub_eq_add_neg] using heq
    obtain ⟨n, hn⟩ := coordinates_exhaustive_mod{p} x y heq'
    exact ⟨n, coordinates_injective hn⟩

theorem generator_injective_mod{p} :
    Function.Injective (fun n : Fin {order} => n.val • gen{p}) := by
  intro a b h
  apply Fin.ext
  apply nsmul_injOn_Iio_addOrderOf (x := gen{p}) _ _ h
  · simp [generator_order_mod{p}]
  · simp [generator_order_mod{p}]

noncomputable def finiteCurveEquiv{p} : Fin {order} ≃ (curve (ZMod {p})).Point :=
  Equiv.ofBijective _ ⟨generator_injective_mod{p}, generator_surjective_mod{p}⟩

noncomputable instance : Fintype (curve (ZMod {p})).Point :=
  Fintype.ofEquiv (Fin {order}) finiteCurveEquiv{p}

theorem curve_card_mod{p} : Fintype.card (curve (ZMod {p})).Point = {order} := by
  rw [← Fintype.card_congr finiteCurveEquiv{p}]
  simp
''')

out.append('end BSDImprovements\n')
Path(__file__).with_name('BSDImprovements').joinpath('FiniteCurve.lean').write_text('\n'.join(out))
